"""Write src/dsan/_build.py with a build number, time and git commit.

    python packaging/stamp_build.py          # before PyInstaller
    python packaging/stamp_build.py --clean  # after, so source runs say "development"

Build number: YYYYMMDD.HHMM (local time) — always increasing, and valid as
macOS CFBundleVersion.
"""
import datetime as dt
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "src" / "dsan" / "_build.py"


def git_commit() -> str:
    try:
        h = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, capture_output=True, text=True,
                           timeout=5).stdout.strip()
        if not h:
            return ""
        dirty = subprocess.run(["git", "status", "--porcelain", "--untracked-files=no"], cwd=ROOT,
                               capture_output=True, text=True, timeout=5).stdout.strip()
        return h + ("-modified" if dirty else "")
    except (OSError, subprocess.SubprocessError):
        return ""


def main() -> int:
    if "--clean" in sys.argv:
        TARGET.unlink(missing_ok=True)
        return 0
    now = dt.datetime.now()
    build = now.strftime("%Y%m%d.%H%M")
    TARGET.write_text(
        "# Generated by packaging/stamp_build.py at build time. Do not edit or commit.\n"
        f'BUILD = "{build}"\n'
        f'BUILT = "{now.strftime("%Y-%m-%d %H:%M")}"\n'
        f'COMMIT = "{git_commit()}"\n', encoding="utf-8")
    print(build)
    return 0


if __name__ == "__main__":
    sys.exit(main())
